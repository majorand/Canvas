export function filterGames({ query = '', category = '', favorites = new Set(), onlyFavorites = false } = {}, catalog = games) {
  const terms = searchable(query).split(/\s+/).filter(Boolean);
  const selectedCategory = searchable(category);
  const saved = favorites instanceof Set ? favorites : new Set(Array.isArray(favorites) ? favorites : []);
  return catalog.filter(game => {
    if (selectedCategory && searchable(game.category) !== selectedCategory) return false;
    if (onlyFavorites && !saved.has(game.id)) return false;
    const text = searchable(game.name + ' ' + game.category);
    return terms.every(term => text.includes(term));
  });
}
export function gameLaunchUrl(game, moduleUrl = import.meta.url) {
  const original = new URL(game.url);
  if (original.protocol !== 'https:' || original.origin !== 'https://www.invisible-character.com' || !original.pathname.startsWith('/activities/') || original.username || original.password) {
    throw new Error('Games must use their original Invisible Character activity page.');
  }
  const launch = appUrl('workspace.html', moduleUrl);
  // URLSearchParams keeps original punctuation in activity slugs intact.
  launch.searchParams.set('goto', game.url);
  return launch;
}
